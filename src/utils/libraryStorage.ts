export function getStoredBooks(): BookItem[] {
  try {
    const raw = localStorage.getItem(LIBRARY_BOOKS_KEY);
    if (!raw) {
      localStorage.setItem(LIBRARY_BOOKS_KEY, JSON.stringify(initialBooks));
      return initialBooks;
    }
    const parsed: BookItem[] = JSON.parse(raw);
    if (!Array.isArray(parsed) || parsed.length === 0) {
      localStorage.setItem(LIBRARY_BOOKS_KEY, JSON.stringify(initialBooks));
      return initialBooks;
    }
    return parsed;
  } catch (e) {
    console.error('Failed to load library books:', e);
    return initialBooks;
  }
}

export function saveStoredBooks(books: BookItem[]): void {
  try {
    localStorage.setItem(LIBRARY_BOOKS_KEY, JSON.stringify(books));
  } catch (e) {
    console.error('Failed to save library books:', e);
  }
}

export function addStoredBook(book: BookItem): BookItem[] {
  const current = getStoredBooks();
  const updated = [book, ...current];
  saveStoredBooks(updated);
  return updated;
}

export function deleteStoredBook(id: string): BookItem[] {
  const current = getStoredBooks();
  const updated = current.filter((b) => b.id !== id);
  saveStoredBooks(updated);
  return updated;
}
